"""医療の決まり（原則17）を、AI への指示とプログラムの確かめで同じ形に守るための部品。

役割：AI への指示に入れる決まりの文と、ツインの文に診断や服薬の指示が出ていないかを確かめる語の一覧を、1か所にまとめる。
4つの極：1. 書く・話す（本人との会話）、4. 10年後に代弁する（代弁、ケアプラン、手紙）。
守る原則：17（してはいけないのは、病気の診断と服薬の指示の2つだけ）。

決まり（tyumajinさんの決定、2026-11-06）
- 診断：病気を推すこと（薬や様子から病気を推す、推測で病名を付ける）と、急ぐかどうかの判定。
- 服薬の指示：薬の量や飲み続けるかの判断と、薬の名前を推して直すこと。
- 一般的な健康の助言、健康の相談、医療の情報をもとにした検討、医療の情報を項目にしたデータ作りは行う。
- 健康の語があるだけで止めたり、答えを作らなかったりしない。病気の多い暮らしでは、体の話が1つ出るたびに
  止まると、ツインが何も言えなくなるため。

プログラムの確かめは、診断や服薬の指示を言い切る形の文だけを見る。「血圧」「薬」のような話題の語では見ない。
話題の語で見ると、本人が話した病気の話に触れただけで答えが止まるため。
関連するテスト：tests/test_medical.py
"""

from __future__ import annotations

# AI への指示に入れる決まりの文。全部の係で同じ文を使い、係ごとに決まりがずれないようにする
RULE = (
    "病気の診断と、服薬の指示はしません。"
    "診断には、薬や様子から病気を推すこと、推測で病名を付けること、急ぐかどうか（すぐ診てもらうか、様子を見てよいか）を決めることが入ります。"
    "服薬の指示には、薬の量や飲み続けるかを決めること、薬の名前を推して直すことが入ります。"
    "そのほかの健康の話（一般的な健康の工夫、体の相談、記録にある病名や医療の情報をもとにした検討）はしてかまいません。"
)

# 健康や病気に関わる問いに添える決まり。止めずに答えるための添え書きで、答えを作らない印ではない
CAVEAT = (
    "（この問いは健康や病気に関わります。止めずに、本人として答えます。医療の情報も材料にしてかまいません。"
    "ただし、病気の診断（急ぐかどうかの判定を含む）と、服薬の指示（量や飲み続けるか、薬の名前を推して直すことを含む）はしません。"
    "そこは、お医者さんか薬剤師さんに聞いてほしいと伝えます）"
)

# 診断や服薬の指示を言い切る形。言い切りの語尾まで含めて見る。
# 「飲まなくても大丈夫かは、お医者さんに」のような、つなぎ先を伝える文を拾わないため
ORDER_PHRASES: tuple[str, ...] = (
    # 服薬の指示（量、飲み続けるか）
    "飲まなくても大丈夫です",
    "飲まなくて大丈夫です",
    "飲まなくてもいいです",
    "飲まなくてもかまいません",
    "やめても大丈夫です",
    "やめてもかまいません",
    "飲むのをやめてください",
    "飲み続けてください",
    "量を減らしてください",
    "量を増やしてください",
    "減らしても大丈夫です",
    "増やしても大丈夫です",
    # 薬の名前を推して直す
    "錠のことですね",
    "錠のことでしょうか",
    "という薬のことですね",
    # 診断（病気を推す）
    "の疑いがあります",
    "の症状です",
    "の兆候です",
    "の始まりです",
    "が高い方ですね",
    "が低い方ですね",
    # 急ぐかどうかの判定
    "すぐに受診してください",
    "急いで受診してください",
    "先に診てもらう必要があります",
    "受診の必要はありません",
    "受診しなくても大丈夫です",
    "様子を見ても大丈夫です",
    "様子を見て大丈夫です",
)


def orders_in(text: str) -> list[str]:
    """文に出てきた、診断や服薬の指示を言い切る形を返す。なければ空。"""
    return [phrase for phrase in ORDER_PHRASES if phrase in text]
